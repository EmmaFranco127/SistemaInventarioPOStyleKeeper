    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        Connection con = null;
        PreparedStatement ps = null;
        ResultSet rs = null;
        
        String producto = cbxProducto.getSelectedItem().toString();
        
        int cantidad = (int) spnCantidad.getValue();
        
        if (cantidad <=0){
            JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida");
            
            return;
        }
        try{
            Conexion cn = new Conexion();
            con = cn.getConnection();
            
            DefaultTableModel modelo = (DefaultTableModel) tblProductos.getModel();
            
            String sql = "SELECT Id_Producto, SKU, Modelo, Existencias FROM producto WHERE Modelo = ?";
            ps = con.prepareStatement(sql);
            ps.setString(1, producto);
            rs = ps.executeQuery();
            
            if(rs.next()){
                
                int idProducto = rs.getInt("Id_Producto");
                boolean existe = false;
                for (int i = 0; i < modelo.getRowCount(); i++){
                    int idTabla = Integer.parseInt(modelo.getValueAt(i, 0).toString());
                    if (idTabla == idProducto){
                        int cantidadActual = Integer.parseInt(modelo.getValueAt(i, 3).toString());
                        int nuevaCantidad = cantidadActual + cantidad;
                        modelo.setValueAt(nuevaCantidad, i, 3);
                        existe = true;
                        break;
                    }
                }
                if(!existe){
                
                Object fila[] = new Object[5];
                
                fila[0] = rs.getInt("Id_Producto");
                fila[1] = rs.getString("SKU");
                fila[2] = rs.getString("Modelo");
                fila[3] = cantidad;
                fila[4] = rs.getInt("Existencias");
                
                modelo.addRow(fila);
                }
                spnCantidad.setValue(0);
                actualizarProductos();
        }
    } catch(Exception e){
           
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
       DefaultTableModel modelo = (DefaultTableModel) tblProductos.getModel();
        
       if (modelo.getRowCount() == 0){
        JOptionPane.showMessageDialog(this, "Agregue al menos un producto");
    return;
    }
        Connection con = null;
        PreparedStatement ps = null;
        ResultSet rs = null;
        
    try{
            Conexion cn = new Conexion();
            con = cn.getConnection();
            
            String sql = "INSERT INTO entradamercancia (Fecha_Ingreso, Notas, Id_Usuario) VALUES (NOW(), ?, ?)";
            ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
            ps.setString(1, txtNotas.getText());
            ps.setInt(2, this.idUsuario);
            ps.executeUpdate();
            
            rs = ps.getGeneratedKeys();
            
            int Id_Entrada = 0;
            if(rs.next()) {
                Id_Entrada = rs.getInt(1);
            }
        String sqlDetalle = "INSERT INTO entradamercancia_producto(Id_EntradaMer, Id_Producto, Cantidad) VALUES (?, ?, ?)";
        PreparedStatement psDetalle = con.prepareStatement(sqlDetalle);
        
            String sqlStock = "UPDATE producto SET Existencias = Existencias + ? WHERE Id_Producto = ?";
            PreparedStatement psStock = con.prepareStatement(sqlStock);
            
            for(int i = 0; i < modelo.getRowCount(); i++){
                    
            int IdProducto = Integer.parseInt(modelo.getValueAt(i,0).toString());
            int cantidad = Integer.parseInt( modelo.getValueAt(i,3).toString());
            
            psDetalle.setInt(1, Id_Entrada);
            psDetalle.setInt(2, IdProducto);
            psDetalle.setInt(3, cantidad);
            
            psDetalle.executeUpdate();
            
            psStock.setInt(1, cantidad);
            psStock.setInt(2, IdProducto);
      
            psStock.executeUpdate();
       }
      
           JOptionPane.showMessageDialog( this, "Entrada guardada correctamente" );
          
        modelo.setRowCount(0);
        txtNotas.setText("");
        spnCantidad.setValue(0);
        actualizarProductos();
        cbxProducto.setSelectedIndex(0);
        
    } catch(Exception e){
           
        JOptionPane.showMessageDialog( this,"Error: " + e.getMessage());
     }
    }//GEN-LAST:event_btnGuardarActionPerformed

