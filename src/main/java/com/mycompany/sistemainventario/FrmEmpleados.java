    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        int fila = tblEmpleados.getSelectedRow();
    if (fila >= 0) {
        String id = tblEmpleados.getValueAt(fila, 0).toString();
        String nom = tblEmpleados.getValueAt(fila, 1).toString();
        String cor = tblEmpleados.getValueAt(fila, 2).toString();
        String log = tblEmpleados.getValueAt(fila, 3).toString();
        String rol = tblEmpleados.getValueAt(fila, 4).toString();
        String pass = "";

        Conexion cc = new Conexion();
        String sql = "SELECT PasswordHash FROM usuario WHERE Id_Usuario = ?";
        
        try (Connection cn = cc.getConnection();
             PreparedStatement ps = cn.prepareStatement(sql)) {
            ps.setString(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    pass = rs.getString("PasswordHash");
                }
            }
            
            FrmNuevoEmpleado fe = new FrmNuevoEmpleado(id,nom, cor, log, rol, pass);
            
            fe.addWindowListener(new java.awt.event.WindowAdapter() {
                @Override
                public void windowClosed(java.awt.event.WindowEvent e) {
                    mostrarDatos(); 
                }
            });
            
            fe.setVisible(true);
            fe.setLocationRelativeTo(null);
            
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al recuperar clave: " + e.getMessage());
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una fila");
    }
    

    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tblEmpleados.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una fila de la tabla.");
        return;
    }

    int id = Integer.parseInt(tblEmpleados.getValueAt(fila, 0).toString());
    String nombre = tblEmpleados.getValueAt(fila, 1).toString();

    int confirmar = javax.swing.JOptionPane.showConfirmDialog(this, 
        "¿Está seguro de eliminar al empleado " + nombre + "?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);

    if (confirmar == javax.swing.JOptionPane.YES_OPTION) {
        String sql = "UPDATE usuario SET Activo = 0 WHERE Id_Usuario = ?";
        Conexion cc = new Conexion();
        try (Connection cn = cc.getConnection();
             PreparedStatement ps = cn.prepareStatement(sql)) {
            
            ps.setInt(1, id);
            ps.executeUpdate();
            
            registrarActividad("Empleados","Eliminar", "Se eliminó el empleado: " + nombre);
            javax.swing.JOptionPane.showMessageDialog(this, "Empleado eliminado.");
            mostrarDatos();
            
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
      }
    }//GEN-LAST:event_btnEliminarActionPerformed

   
