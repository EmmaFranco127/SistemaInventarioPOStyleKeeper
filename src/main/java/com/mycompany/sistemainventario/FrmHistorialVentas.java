    public void consultarVentas(String fechaInicio, String fechaFin, String producto) {
        if (!Sesion.puedeVentas()
            || Sesion.getIdUsuario() != idUsuario) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No tienes permiso para consultar el historial de ventas.",
            "Acceso restringido",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

            return;
        }
        modeloVentas.setRowCount(0);

        StringBuilder sql = new StringBuilder(
            "SELECT v.Id_Venta, v.Fecha_Hora, "
            + "GROUP_CONCAT(CONCAT(vp.Cantidad, 'x ', p.Modelo, ' (', p.Talla, ')') SEPARATOR ', ') AS ResumenProductos, "
            + "u.Nombre AS Usuario, v.Total, v.Estado "
            + "FROM venta v "
            + "INNER JOIN usuario u ON v.Id_Usuario = u.Id_Usuario "
            + "INNER JOIN venta_producto vp ON v.Id_Venta = vp.Id_Venta "
            + "INNER JOIN producto p ON vp.Id_Producto = p.Id_Producto "
            + "WHERE 1=1 "
        );

    java.util.List<Object> parametros = new java.util.ArrayList<>();

    if (!fechaInicio.isEmpty()) {
        sql.append("AND DATE(v.Fecha_Hora) >= ? ");
        parametros.add(fechaInicio);
    }
    if (!fechaFin.isEmpty()) {
        sql.append("AND DATE(v.Fecha_Hora) <= ? ");
        parametros.add(fechaFin);
    }
    if (!producto.isEmpty()) {
            sql.append("AND v.Id_Venta IN ("
                    + "SELECT vp2.Id_Venta FROM venta_producto vp2 "
                    + "INNER JOIN producto p2 ON vp2.Id_Producto = p2.Id_Producto "
                    + "WHERE p2.Modelo LIKE ? OR p2.SKU LIKE ?) ");
            parametros.add("%" + producto + "%");
            parametros.add("%" + producto + "%");
        }
    
    sql.append("GROUP BY v.Id_Venta, v.Fecha_Hora, u.Nombre, v.Total, v.Estado ");
    sql.append("ORDER BY v.Fecha_Hora DESC");

    Conexion cc = new Conexion();
    try (java.sql.Connection cn = cc.getConnection();
         java.sql.PreparedStatement ps = cn.prepareStatement(sql.toString())) {

        for (int i = 0; i < parametros.size(); i++) {
            ps.setObject(i + 1, parametros.get(i));
        }

        java.sql.ResultSet rs = ps.executeQuery();
        boolean hayDatos = false;

        while (rs.next()) {
            hayDatos = true;
            modeloVentas.addRow(new Object[]{
                rs.getInt("Id_Venta"),
                rs.getString("Fecha_Hora"),
                rs.getString("ResumenProductos"),
                rs.getString("Usuario"),
                "$" + String.format("%.2f", rs.getDouble("Total")),
                rs.getString("Estado")
            });
        }

        if (!hayDatos) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "No se encontraron ventas con los criterios ingresados.",
                "Aviso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al consultar ventas: " + e.getMessage());
    }
   }
    
