    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        // TODO add your handling code here:
    String user = txtLogin.getText(); 
    String pass = new String(txtContraseña.getPassword());
    
    String sql = "SELECT Id_Usuario, Nombre, Login, Rol FROM usuario WHERE Login = ? AND PasswordHash = ? AND Activo = 1";
    
    Conexion cc = new Conexion();
    try (Connection cn = cc.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {
        
        ps.setString(1, user);
        ps.setString(2, pass);
        ResultSet rs = ps.executeQuery();
        
        if (rs.next()) {
            int idUsuario = rs.getInt("Id_Usuario");
            String nombreReal = rs.getString("Nombre");
            String loginReal = rs.getString("Login");
            String rolAsignado = rs.getString("Rol");
            
            Sesion.iniciar(idUsuario, rolAsignado);
            
            FrmDashboard dashboard = new FrmDashboard(idUsuario,nombreReal,loginReal,rolAsignado);
            dashboard.setVisible(true);
            this.dispose();
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos");
        }
        
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error de sistema: " + e.getMessage());
    }
    }//GEN-LAST:event_btnIniciarActionPerformed

