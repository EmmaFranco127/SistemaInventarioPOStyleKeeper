    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText().trim();
        String descripcion = txtDescripcion.getText().trim();
        
        boolean esEdicion = !idCategoria.isEmpty();
        
        if(nombre.isEmpty() || descripcion.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.");
            return;
        }
        if (existeCategoria(nombre, idCategoria)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ya existe una categoría con ese nombre.");
    return;
}
        String sql;
        
        if(esEdicion){
            sql = "UPDATE categoria SET nombre=?, Descripcion=? WHERE Id_Categoria=?";
        }else{
             sql = "INSERT INTO categoria (Nombre, Descripcion, Activo) VALUES (?, ?, 1)";
        }
        
        Conexion cc = new Conexion();
        
        try (Connection cn = cc.getConnection();
             PreparedStatement ps = cn.prepareStatement(sql)) {
            
            ps.setString(1, nombre);
            ps.setString(2, descripcion);
            
            if (esEdicion){
                ps.setString(3, idCategoria);
            }
            
            int resultado = ps.executeUpdate();
            
            if(resultado > 0){
                if (esEdicion){
                    
                    registrarActividad("Categorias", "Editar", "Se edito la nueva categoría: " + nombre);
                }else{
                    registrarActividad("Categorias", "Registrar", "Se registró una nueva categoría: " + nombre);
            }
                javax.swing.JOptionPane.showMessageDialog(this, "Guardado correctamente.");
                this.dispose();
            }
        } catch (SQLException e){
            
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

