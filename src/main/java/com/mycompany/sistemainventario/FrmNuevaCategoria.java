public void registrarActividad(String modulo, String accion, String descripcion) {

    String sql = "INSERT INTO actividad_reciente(Modulo, Accion, Descripcion, FechaHora) "
               + "VALUES (?, ?, ?, NOW())";

    Conexion cc = new Conexion();

    try (Connection cn = cc.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {

        ps.setString(1, modulo);
        ps.setString(2, accion);
        ps.setString(3, descripcion);

        ps.executeUpdate();

    } catch (SQLException e) {
        System.out.println("Error al registrar actividad: " + e.getMessage());
    }
}
public boolean existeCategoria(String nombre, String idActual) {
    String sql;

    if (idActual != null && !idActual.isEmpty()) {
        sql = "SELECT COUNT(*) FROM categoria WHERE Nombre = ? AND Id_Categoria <> ?";
    } else {
        sql = "SELECT COUNT(*) FROM categoria WHERE Nombre = ?";
    }
        Conexion cc = new Conexion();
    try (Connection cn = cc.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {

        ps.setString(1, nombre);

        if (idActual != null && !idActual.isEmpty()) {
            ps.setString(2, idActual);
        }
        ResultSet rs = ps.executeQuery();
        if (rs.next()) {
            return rs.getInt(1) > 0;
        }
    } catch (SQLException e) {
        System.out.println("Error al validar categoría: " + e.getMessage());
    }
    return false;
}

