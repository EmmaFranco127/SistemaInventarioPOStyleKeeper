    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
    String nombre = txtNombre.getText().trim();
    String correo = txtCorreo.getText().trim();
    String login = txtLogin.getText().trim();
    String rol = cbxRol.getSelectedItem().toString();
    String pass = new String(txtContraseña.getPassword());

    boolean esEdicion = (idEmpleado != null && !idEmpleado.isEmpty());

    if (nombre.isEmpty() || login.isEmpty() || pass.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.");
        return;
    }

    String sql;

    if (esEdicion) {
        sql = "UPDATE usuario SET Nombre=?, Correo=?, Login=?, Rol=?, PasswordHash=? WHERE Id_Usuario=?";
    } else {
        sql = "INSERT INTO usuario (Nombre, Correo, Login, Rol, PasswordHash, Activo) VALUES (?, ?, ?, ?, ?, 1)";
    }

    Conexion cc = new Conexion();


    try (Connection cn = cc.getConnection()) {

        String sqlValidar;
        if (esEdicion) {
            sqlValidar = "SELECT COUNT(*) FROM usuario WHERE Login = ? AND Id_Usuario <> ?";
        } else {
            sqlValidar = "SELECT COUNT(*) FROM usuario WHERE Login = ?";
        }

        PreparedStatement psValidar = cn.prepareStatement(sqlValidar);
        psValidar.setString(1, login);

        if (esEdicion) {
            psValidar.setString(2, idEmpleado);
        }

        ResultSet rs = psValidar.executeQuery();

        if (rs.next() && rs.getInt(1) > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "El usuario ya existe.");
            return;
        }
        
        PreparedStatement ps = cn.prepareStatement(sql);

        ps.setString(1, nombre);
        ps.setString(2, correo);
        ps.setString(3, login);
        ps.setString(4, rol);
        ps.setString(5, pass);

        if (esEdicion) {
            ps.setString(6, idEmpleado);
        }

        int resultado = ps.executeUpdate();
        if (resultado > 0) {

            if (esEdicion) {

                registrarActividad("Empleados","Editar","Se actualizó el empleado: " + nombre);

            } else {

                registrarActividad( "Empleados", "Registrar","Se registró un nuevo empleado: " + nombre);
            }

            javax.swing.JOptionPane.showMessageDialog(this, "Guardado correctamente.");
            this.dispose();
        }

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }  
    }//GEN-LAST:event_btnGuardarActionPerformed

