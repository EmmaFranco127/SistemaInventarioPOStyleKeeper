    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText().trim();
        String contacto = txtContacto.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String correo = txtCorreo.getText().trim();
        
        boolean esEdicion = (idProveedor != null && !idProveedor.isEmpty());
        System.out.println("ID PROVEEDOR = " + idProveedor);
        System.out.println("ES EDICION = " + esEdicion);
    if (nombre.isEmpty() || contacto.isEmpty() || telefono.isEmpty() || correo.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.");
    return;
    }
    if (!correo.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$")){
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un correo válido");
        return;
    }
    if (existeProveedor(nombre, correo)) {
    javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un proveedor con ese nombre o correo");
    return;
}
    String sql;
    
    if (esEdicion) {
        sql = "UPDATE proveedor SET Nombre=?, contacto=?, telefono=?, correo=? WHERE Id_Proveedor=?";
    } else {
        sql = "INSERT INTO proveedor (Nombre, Contacto, Telefono, Correo) VALUES (?, ?, ?, ?)";
    }
    Conexion cc = new Conexion();
    
    try (Connection cn = cc.getConnection();
    PreparedStatement ps = cn.prepareStatement(sql)) {
        
                ps.setString(1, nombre);
                ps.setString(2, contacto);
                ps.setString(3, telefono);
                ps.setString(4, correo);
                
            if (esEdicion) {
            ps.setString(5, idProveedor);
        }
            
                    int resultado = ps.executeUpdate();
        if (resultado > 0) {

            if (esEdicion) {

                registrarActividad("Proveedor","Editar","Se actualizó el proveedor: " + nombre);

            } else {

                registrarActividad( "Proveedor", "Registrar","Se registró un nuevo proveedor: " + nombre);
            }

            javax.swing.JOptionPane.showMessageDialog(this, "Guardado correctamente.");
            this.dispose();
        }

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }  


    }//GEN-LAST:event_btnGuardarActionPerformed

