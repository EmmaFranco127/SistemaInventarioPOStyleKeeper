public void cargarDatos() {

    String sql = "SELECT Nombre, Correo, Login, Rol FROM usuario WHERE Id_Usuario = ?";

    Conexion cc = new Conexion();

    try (Connection cn = cc.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {
        ps.setInt(1, idUsuario);
        ResultSet rs = ps.executeQuery();

        if (rs.next()) {

            lblNombre.setText(rs.getString("Nombre"));
            lblCorreo.setText(rs.getString("Correo"));
            lblLogin.setText(rs.getString("Login"));
            lblRol.setText(rs.getString("Rol"));
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Error al cargar datos: " + e.getMessage());
    }
}
