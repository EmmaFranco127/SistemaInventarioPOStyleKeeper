    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String contrasenaActualInput = new String(txtContraseñaActual.getPassword()).trim();
        String nuevaContrasenaInput = new String(txtNuevaContraseña.getPassword()).trim();

        if (contrasenaActualInput.isEmpty() || nuevaContrasenaInput.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Por favor, verifique los datos. Ambos campos de contraseña son obligatorios.",
                "Error de Validación",
                javax.swing.JOptionPane.ERROR_MESSAGE);
            limpiarCamposContrasena();
            return;
        }

        if (nuevaContrasenaInput.length() < 6) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, verifique los datos. La nueva contraseña debe tener un mí­nimo de 6 caracteres.",
                    "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            limpiarCamposContrasena();
            return;
        }
        if (contrasenaActualInput.equals(nuevaContrasenaInput)) {
            javax.swing.JOptionPane.showMessageDialog(this,
        "La nueva contraseña debe ser diferente a la actual.");
    limpiarCamposContrasena();
    return;
}
        String validarSql = "SELECT * FROM usuario WHERE Id_Usuario = ? AND PasswordHash = ?";
        try (Connection cn = new Conexion().getConnection();
            PreparedStatement psValidar = cn.prepareStatement(validarSql)) {
            psValidar.setInt(1, idUsuario);
            psValidar.setString(2, contrasenaActualInput);

        try (ResultSet rs = psValidar.executeQuery()) {
        if (!rs.next()) {
            javax.swing.JOptionPane.showMessageDialog(this,"La contraseña actual es incorrecta");
            limpiarCamposContrasena();
            return;
        }
    
    }
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(     this,"Error al validar contraseña: " + e.getMessage());
    return;
}

        java.sql.Connection con = null;
        java.sql.PreparedStatement ps = null;
        String sql = "UPDATE usuario SET PasswordHash = ? WHERE Id_Usuario = ?";

        try {
            com.mycompany.sistemainventario.Conexion conectar = new com.mycompany.sistemainventario.Conexion();
            con = conectar.getConnection();

            if (con != null) {
                ps = con.prepareStatement(sql);
                ps.setString(1, nuevaContrasenaInput);
                ps.setInt(2, this.idUsuario);

                int filasAfectadas = ps.executeUpdate();

                if (filasAfectadas > 0) {
      
                String sqlActividad = "INSERT INTO actividad_reciente (Descripcion, FechaHoraVALUES (?,NOW())";
                try (PreparedStatement psActividad = con.prepareStatement(sqlActividad)){
                   psActividad.setString(1, lblNombre.getText() + "cambio su contraseña");
                   psActividad.executeUpdate();
                }
                javax.swing.JOptionPane.showMessageDialog(this,
                        "La contraseña se actualizo correctamente.",
                        "Exito",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE);

                    
                    limpiarCamposContrasena();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this,
                        "No se pudo actualizar la contraseña. Intente de nuevo.",
                        "Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Error al establecer conexión con el servidor MySQL.",
                    "Error de Conexión",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Error al conectar con la base de datos: " + e.getMessage(),
                "Error Cri­tico",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        } finally {
            try { if (ps != null) ps.close(); } catch (Exception e) {}
            try { if (con != null) con.close(); } catch (Exception e) {}
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

