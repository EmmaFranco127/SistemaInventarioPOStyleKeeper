    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
                   int fila = tblProveedor.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una fila de la tabla.");
        return;
    }

    int id = Integer.parseInt(tblProveedor.getValueAt(fila, 0).toString());
    String nombre = tblProveedor.getValueAt(fila, 1).toString();

    int confirmar = javax.swing.JOptionPane.showConfirmDialog(this, 
        "¿Está seguro de eliminar al proveedor " + nombre + "?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);

    if (confirmar == javax.swing.JOptionPane.YES_OPTION) {
        String sql = "UPDATE proveedor SET Activo = 0 WHERE Id_Proveedor = ?";
        Conexion cc = new Conexion();
        try (Connection cn = cc.getConnection();
             PreparedStatement ps = cn.prepareStatement(sql)) {
            
            ps.setInt(1, id);
            ps.executeUpdate();
            
            registrarActividad("Proveedor","Eliminar", "Se eliminó el proveedor: " + nombre); 
            javax.swing.JOptionPane.showMessageDialog(this, "Proveedor eliminado.");
            mostrarDatos();
            
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
      }  
    }//GEN-LAST:event_btnEliminarActionPerformed

