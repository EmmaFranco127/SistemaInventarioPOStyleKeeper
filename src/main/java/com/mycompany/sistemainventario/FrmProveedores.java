    public void mostrarDatos() {
        String[] titulos = {"ID", "Nombre", "Contacto", "Telefono", "Correo"};
        String[] registros = new String[5];
        DefaultTableModel modelo = new DefaultTableModel(null, titulos);
        
        String sql = "SELECT * FROM proveedor WHERE Activo = 1";
        
        Conexion cc = new Conexion();
        try (Connection cn = cc.getConnection();
             PreparedStatement ps = cn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            
            while (rs.next()) {
                registros[0] = rs.getString("Id_Proveedor");
                registros[1] = rs.getString("Nombre");
                registros[2] = rs.getString("Contacto");
                registros[3] = rs.getString("Telefono");
                registros[4] = rs.getString("Correo");
                modelo.addRow(registros);
            }
            tblProveedor.setModel(modelo); 
            tblProveedor.getColumnModel().getColumn(0).setMinWidth(0);
            tblProveedor.getColumnModel().getColumn(0).setMaxWidth(0);
            tblProveedor.getColumnModel().getColumn(0).setWidth(0);
            tblProveedor.getColumnModel().getColumn(0).setPreferredWidth(0);
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar tabla: " + e.getMessage());
        }
    }
    
    public void buscarDatos(String valor) {
    String[] titulos = {"ID", "Nombre", "Contacto", "Telefono", "Correo"};
    String[] registros = new String[5];
    DefaultTableModel modelo = new DefaultTableModel(null, titulos);

    String sql = "SELECT Id_Proveedor, Nombre, Contacto, Telefono, Correo FROM proveedor "
               + "WHERE (Nombre LIKE ? OR Contacto LIKE ?) AND Activo = 1";

    Conexion cc = new Conexion();
    try (Connection cn = cc.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {
        
        ps.setString(1, "%" + valor + "%");
        ps.setString(2, "%" + valor + "%");
        
        try (ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                registros[0] = rs.getString("Id_Proveedor");
                registros[1] = rs.getString("Nombre");
                registros[2] = rs.getString("Contacto");
                registros[3] = rs.getString("Telefono");
                registros[4] = rs.getString("Correo");
                modelo.addRow(registros);
            }
            tblProveedor.setModel(modelo);
            tblProveedor.getColumnModel().getColumn(0).setMinWidth(0);
            tblProveedor.getColumnModel().getColumn(0).setMaxWidth(0);
            tblProveedor.getColumnModel().getColumn(0).setWidth(0);
            tblProveedor.getColumnModel().getColumn(0).setPreferredWidth(0);
        }
    } catch (SQLException e) {
        System.out.println("Error al filtrar: " + e.getMessage());
    }
}
    
    
    public void registrarActividad(String modulo, String accion, String descripcion) {

    String sql = "INSERT INTO actividad_reciente(Modulo, Accion, Descripcion, FechaHora) "
               + "VALUES (?, ?, ?, NOW())";

    Conexion cc = new Conexion();

    try (Connection cn = cc.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {

        ps.setString(1, modulo);
        ps.setString(2, accion);
        ps.setString(3, descripcion);

        ps.executeUpdate();

    } catch (SQLException e) {
        System.out.println("Error al registrar actividad: " + e.getMessage());
    }
}
