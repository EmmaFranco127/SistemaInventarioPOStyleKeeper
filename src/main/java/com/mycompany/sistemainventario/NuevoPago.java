    public void registrarActividad(String modulo, String accion, String descripcion){
        String sql = "INSERT INTO actividad_reciente(Modulo, Accion, Descripcion, FechaHora) VALUES (?,?,?, NOW())";
        Conexion cc = new Conexion();
        try (Connection cn = cc.getConnection();
                PreparedStatement ps = cn.prepareStatement(sql)){
            ps.setString(1, modulo);
            ps.setString(2, accion);
            ps.setString(3, descripcion);
            ps.executeUpdate();
        }catch (SQLException e){
            System.out.println("Error al registrar actividad: " + e.getMessage());
        }
    }
    public void cargarProveedores(){
        try{
            Conexion cc = new Conexion();
            Connection cn = cc.getConnection();
            
            String sql = "SELECT Nombre FROM proveedor ORDER BY Nombre";
            
            PreparedStatement ps = cn.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();
            
            cmbProveedor.removeAllItems();
            cmbProveedor.addItem("Seleccionar proveedor");
            
            while(rs.next()){
                cmbProveedor.addItem(rs.getString("Nombre"));
            }
        }catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error al cargar provedores: " + e.getMessage());
           
            
        }
    }
