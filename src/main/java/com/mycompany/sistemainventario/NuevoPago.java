    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        if(cmbProveedor.getSelectedIndex() == 0){
        JOptionPane.showMessageDialog(this, "Seleccione un proveedor");
        return;
    }
        
        Conexion cc = new Conexion();
        try (Connection cn = cc.getConnection()) {
            double monto = Double.parseDouble(txtMonto.getText());
           java.util.Date fechaSeleccionada = dateFecha.getDate();
           java.sql.Timestamp fechaHora = new java.sql.Timestamp(fechaSeleccionada.getTime()
        );
            String concepto = txtConcepto.getText();
            String proveedor = cmbProveedor.getSelectedItem().toString();
            String sqlProveedor = "SELECT Id_Proveedor FROM proveedor WHERE Nombre = ?";
            PreparedStatement psProveedor = cn.prepareStatement(sqlProveedor);
            psProveedor.setString(1, proveedor);
            ResultSet rsProveedor = psProveedor.executeQuery();
            int idProveedor = 0;
            if(rsProveedor.next()){
                idProveedor = rsProveedor.getInt("Id_Proveedor");
            }
         
            if(esEdicion){
            String sql = "UPDATE pagoproveedor SET Monto=?, Fecha_Pago=?, Concepto=?, Id_Proveedor=?, Id_Usuario=? WHERE Id_PagoProveedor=?";
            PreparedStatement ps = cn.prepareStatement(sql);

            ps.setDouble(1,monto);
            ps.setTimestamp(2, fechaHora);
            ps.setString(3, concepto);
            ps.setInt(4, idProveedor);
            ps.setInt(5, this.idUsuario);
            ps.setInt(6, idPagoProveedor);

            ps.executeUpdate();

    registrarActividad("Pago a Proveedores", "Actualización",
            "Se actualizó el pago de $ " + monto + " al proveedor " + proveedor);
    

    JOptionPane.showMessageDialog(this, "Pago actualizado correctamente");

}else{
    String sql ="INSERT INTO pagoproveedor (Monto, Fecha_Pago, Concepto, Id_Proveedor, Id_Usuario) VALUES(?, ?, ?, ?, ?)";

    PreparedStatement ps = cn.prepareStatement(sql);

    ps.setDouble(1,monto);
    ps.setTimestamp(2, fechaHora);
    ps.setString(3, concepto);
    ps.setInt(4, idProveedor);
    ps.setInt(5, this.idUsuario);

    ps.executeUpdate();

    registrarActividad("Pago a Proveedores", "Registro",
            "Se registró un pago de $ " + monto + " al proveedor " + proveedor);

    JOptionPane.showMessageDialog(this, "Pago registrado correctamente");
    }
     if(formulario != null){
    formulario.mostrarPagos();
    formulario.calcularTotal();
    formulario.setVisible(true);
     }
            this.dispose();

        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error" + e.getMessage());

        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

