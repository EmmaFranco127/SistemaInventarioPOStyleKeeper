    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        Connection con = null;
        PreparedStatement ps = null;
        ResultSet rs = null;

        try{
            if(cbxProducto.getSelectedIndex() == 0){
                JOptionPane.showMessageDialog(this, "Seleccione un producto");
                return; 
            }
            
            String producto = cbxProducto.getSelectedItem().toString();
            int cantidad = Integer.parseInt(spnCantidad.getValue().toString());
            if(cantidad <=0){
                JOptionPane.showMessageDialog(this,"Ingrese una cantidad válida");
                return;
            }
            
            Conexion cn = new Conexion();
            con = cn.getConnection();

            DefaultTableModel modelo = (DefaultTableModel) tblProductos.getModel();

            String sql = "SELECT Id_Producto, SKU, Modelo, Existencias FROM producto WHERE Modelo = ?";
            ps = con.prepareStatement(sql);
            ps.setString(1, producto);
            rs = ps.executeQuery();

            if(rs.next()){
                
                int existencias = rs.getInt("Existencias");
                
                for(int i = 0; i < modelo.getRowCount(); i++){
                    String productoTabla = modelo.getValueAt(i, 2).toString();
                    
                    if(productoTabla.equals(producto)){
                    int cantidadActual = Integer.parseInt(modelo.getValueAt(i, 3).toString());
                    int nuevaCantidad = cantidadActual + cantidad;
                    if (nuevaCantidad > existencias){
                         JOptionPane.showMessageDialog(this, "No hay suficientes existencias\n" + "Existencias disponibles: " + existencias);
                return;
                    }
                    modelo.setValueAt(nuevaCantidad, i,3);
                    actualizarProductos();
                    return;
                }
            }
                if(cantidad > existencias){
                    JOptionPane.showMessageDialog(this, "No hay suficientes existencias");
                    return;
                }
                Object fila[] = new Object[5];

                fila[0] = rs.getInt("Id_Producto");
                fila[1] = rs.getString("SKU");
                fila[2] = rs.getString("Modelo");
                fila[3] = cantidad;
                fila[4] = rs.getInt("Existencias");
                
                modelo.addRow(fila);
                
                actualizarProductos();
            }
        } catch(Exception e){

            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        Connection con = null;
        PreparedStatement ps = null;
        ResultSet rs = null;

        try{
            Conexion cn = new Conexion();
            con = cn.getConnection();
            con.setAutoCommit(false);
            DefaultTableModel modelo = (DefaultTableModel) tblProductos.getModel();
            
            if(cbxMotivo.getSelectedIndex() == 0){
                JOptionPane.showMessageDialog(this, "Seleccione un motivo");
                return;
}
            if(modelo.getRowCount() == 0){
                JOptionPane.showMessageDialog(this, "Agregue al menos un producto");
                return;
}

           
            String sql = "INSERT INTO salidamercancia (Fecha, Motivo, Notas, Id_Usuario) VALUES (NOW(), ?, ?,?)";
            ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);

            ps.setString(1, cbxMotivo.getSelectedItem().toString());
            ps.setString(2, txtNotas.getText());
            ps.setInt(3, idUsuario);
            ps.executeUpdate();

            rs = ps.getGeneratedKeys();

            int Id_Salida = 0;
            if(rs.next()) {
                Id_Salida = rs.getInt(1);
            }
            String sqlDetalle = "INSERT INTO salidamercancia_producto(Id_SalidaMer, Id_Producto, Cantidad) VALUES (?, ?, ?)";
            PreparedStatement psDetalle = con.prepareStatement(sqlDetalle);

            for(int i = 0; i < modelo.getRowCount(); i++){

                int IdProducto = Integer.parseInt(modelo.getValueAt(i,0).toString());
                int cantidad = Integer.parseInt( modelo.getValueAt(i,3).toString());
                
                String sqlValidar = "SELECT Existencias FROM producto WHERE Id_Producto = ?"; 
                PreparedStatement psValidar = con.prepareStatement(sqlValidar);
                
                psValidar.setInt(1, IdProducto);
                ResultSet rsValidar = psValidar.executeQuery();
                if(rsValidar.next()){
                    int stockActual = rsValidar.getInt("Existencias");
                    if (cantidad > stockActual){
                      JOptionPane.showMessageDialog(this, "Stock insuficiente para uno de los productos");
                      con.rollback();
                      return;
                    }
                }
                

                psDetalle.setInt(1, Id_Salida);
                psDetalle.setInt(2, IdProducto);
                psDetalle.setInt(3, cantidad);

                psDetalle.executeUpdate();

                String sqlStock = "UPDATE producto SET Existencias = Existencias - ? WHERE Id_Producto = ?";
                PreparedStatement psStock = con.prepareStatement(sqlStock);
                psStock.setInt(1, cantidad);
                psStock.setInt(2, IdProducto);

                psStock.executeUpdate();
            }
            con.commit();
            JOptionPane.showMessageDialog( this, "Salida guardada correctamente" );
               
            
            modelo.setRowCount(0);
            txtNotas.setText("");
            spnCantidad.setValue(0);
            lblProductos.setText("0");
            cbxProducto.setSelectedIndex(0);
            cbxMotivo.setSelectedIndex(0);

        } catch(Exception e){
            try{
                if(con !=null){
                    con.rollback();
                }
            }catch(SQLException ex){
                JOptionPane.showMessageDialog(this, "Error rollback" + ex.getMessage());
            }

            JOptionPane.showMessageDialog( this,"Error: " + e.getMessage());
            
        }finally{
            try{
                if(con != null){
                    con.setAutoCommit(true);
                    con.close();
                }
                }catch(SQLException ex){
                        JOptionPane.showMessageDialog(this, "Error la cerrar coneción: " + ex.getMessage());
                        }
            }
    }//GEN-LAST:event_btnGuardarActionPerformed

